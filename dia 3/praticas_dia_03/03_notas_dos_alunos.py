notas = [7, 5, 9, 6]

print(notas)
notas.append(8)        # Adiciona 8 ao final
print(notas)
notas.pop()            # Remove o último elemento
print(notas)
notas.insert(1, 10)    # Insere 10 no índice 1
print(notas)
notas.remove(5)        # Remove o valor 5
print(notas)
notas.sort()           # Ordena em ordem crescente

print(notas)
print("Quantidade:", len(notas))

