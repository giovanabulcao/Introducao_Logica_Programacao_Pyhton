# Uma lista armazena vários elementos em uma única variável.
# Podemos utilizá-la para organizar nomes, notas, preços e outros dados.
# Os elementos mantêm uma ordem e podem ser acessados por índices.
# O primeiro índice é 0. Listas também podem ser modificadas.

nomes = ["Ana", "Bruno", "Carla"]
print("Lista de nomes:", nomes)
print("Primeiro nome:", nomes[0])
